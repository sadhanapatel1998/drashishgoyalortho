                    <article class="content-block" id="what-is-pmjay">
                        <h3 class="content-block-title">
                            <i class="bi bi-info-circle-fill"></i>
                            <span>1. What is Ayushman Bharat (PM-JAY)?</span>
                        </h3>
                        <p class="service-body-text">
                            <strong>Ayushman Bharat Pradhan Mantri Jan Arogya Yojana (AB-PMJAY)</strong> is the flagship
                            national public health insurance scheme launched by the Government of India. Designed to
                            achieve Universal Health Coverage (UHC), it is officially the world’s largest
                            government-funded healthcare assurance program, safeguarding over 55 crore vulnerable and
                            economically weaker citizens (bottom 40% of India’s population).
                        </p>
                        <p class="service-body-text">
                            Under this visionary healthcare program, each eligible family receives an annual health
                            coverage pool of <strong>₹5,00,000 (Five Lakh Rupees)</strong> for secondary and tertiary
                            care hospitalization across public and empaneled private network hospitals across India.
                            There is no ceiling on family size, age, or gender, ensuring that senior citizens and women
                            receive complete medical protection without financial hardship.
                        </p>
                    </article>

